// Command gen writes fields_gen.go: the field sets and object builders for 0
// to maxArity components, each a field or a flat decoder. A set with a flat
// component moves to the flatFields types, whose objects have no Strict.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// maxArity is the most components one set holds: the arity of the function
// given to Map. Flat nests sets, so it does not limit the fields of an object.
const maxArity = 16

var letters = strings.Split("ABCDEFGHIJKLMNOP", "")

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen. DO NOT EDIT.\n\npackage raoh\n\nimport \"slices\"\n")
	for n := 0; n <= maxArity; n++ {
		writeArity(&b, n, false)
		if n > 0 {
			writeArity(&b, n, true)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("%v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile("fields_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// params returns "[A, B any]" and "[A, B]" for n type parameters, or "" for 0.
func params(n int) (decl, use string) {
	if n == 0 {
		return "", ""
	}
	ls := strings.Join(letters[:n], ", ")
	return "[" + ls + " any]", "[" + ls + "]"
}

func join(n int, f func(i int) string) string {
	s := make([]string, n)
	for i := range n {
		s[i] = f(i)
	}
	return strings.Join(s, ", ")
}

// writeArity writes the set and the object builder of n components. A flat
// set has at least one Flat, so its declared fields are not known and its
// object has no Strict; flat sets of 0 components do not exist.
func writeArity(b *bytes.Buffer, n int, flat bool) {
	decl, use := params(n)
	prefix := ""
	if flat {
		prefix = "flat"
	}
	fields := fmt.Sprintf("%sfields%d", prefix, n)
	object := fmt.Sprintf("%sobject%d", prefix, n)
	p := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }

	p("\n// %s is a set of %d components.\ntype %s%s struct {\n", fields, n, fields, decl)
	if !flat {
		p("\tnames []string\n")
	}
	for i := range n {
		p("\tp%d part[%s]\n", i, letters[i])
	}
	p("}\n")

	if n < maxArity {
		next := letters[n]
		nextUse := "[" + strings.Join(letters[:n+1], ", ") + "]"
		// with returns the components the set holds followed by last.
		with := func(last string) string {
			parts := make([]string, 0, n+1)
			for i := range n {
				parts = append(parts, fmt.Sprintf("f.p%d", i))
			}
			return strings.Join(append(parts, last), ", ")
		}
		if flat {
			p("\n// Field returns the set with one more field, name, read with src.\n")
			p("func (f %s%s) Field[%s any](name string, src FieldSource[%s]) flatfields%d%s {\n", fields, use, next, next, n+1, nextUse)
			p("\treturn flatfields%d%s{%s}\n}\n", n+1, nextUse, with("toPart(name, src)"))
		} else {
			p("\n// Field returns the set with one more field, name, read with src.\n")
			p("func (f %s%s) Field[%s any](name string, src FieldSource[%s]) fields%d%s {\n", fields, use, next, next, n+1, nextUse)
			p("\treturn fields%d%s{append(slices.Clip(f.names), name), %s}\n}\n", n+1, nextUse, with("toPart(name, src)"))
		}
		p("\n// Flat returns the set with one more component, d, read from the same\n// object as the fields: d is given the object itself, at the path of the\n// object, and its value is the next argument of the function given to Map.\n// The members d reads are not known, so an object with a Flat has no Strict.\n")
		p("func (f %s%s) Flat[%s any](d DecoderOf[%s]) flatfields%d%s {\n", fields, use, next, next, n+1, nextUse)
		p("\treturn flatfields%d%s{%s}\n}\n", n+1, nextUse, with("toFlatPart(d)"))
	}

	p("\nfunc (f %s%s) object() %s%s { return %s%s{f: f} }\n", fields, use, object, use, object, use)

	if flat {
		p("\n// %s builds the decoder of an object of %d components, some of them Flat.\ntype %s%s struct {\n\tf %s%s\n}\n", object, n, object, decl, fields, use)
	} else {
		p("\n// %s builds the decoder of an object of %d fields.\ntype %s%s struct {\n\tf      %s%s\n\tstrict bool\n}\n", object, n, object, decl, fields, use)
		p("\n// Strict reports unknown_field for each member the fields do not name.\n")
		p("func (o %s%s) Strict() %s%s {\n\to.strict = true\n\treturn o\n}\n", object, use, object, use)
	}

	args := join(n, func(i int) string { return fmt.Sprintf("v%d %s", i, letters[i]) })
	vals := join(n, func(i int) string { return fmt.Sprintf("v%d", i) })
	types := join(n, func(i int) string { return letters[i] })
	strict := "\t\tif o.strict {\n\t\t\tc.unknown(m, at, o.f.names)\n\t\t}\n"
	if flat {
		strict = ""
	}

	p("\n// Map returns the decoder that builds the value with fn once every component\n// has decoded.\n")
	p("func (o %s%s) Map[R any](fn func(%s) R) Decoder[any, R] {\n", object, use, types)
	p("\trequireArgument(fn != nil, \"%s.Map\", \"fn\")\n", "Object")
	p("\treturn o.AndThen(func(%s) (R, error) { return fn(%s), nil })\n}\n", args, vals)

	p("\n// AndThen returns the decoder that builds the value with fn once every\n// component has decoded. Issues fn returns (see Invalid) are reported at the\n// object; any other error stops the decode.\n")
	p("func (o %s%s) AndThen[R any](fn func(%s) (R, error)) Decoder[any, R] {\n", object, use, types)
	p("\trequireArgument(fn != nil, \"%s.AndThen\", \"fn\")\n", "Object")
	p("\treturn Decoder[any, R]{func(in any, at Path) outcome[R] {\n")
	p("\t\tm, issue := openObject(in, at)\n\t\tif issue != nil {\n\t\t\treturn invalid[R](*issue)\n\t\t}\n")
	p("\t\tvar c collector\n")
	for i := range n {
		p("\t\tv%d := read(&c, o.f.p%d, in, m, at)\n", i, i)
	}
	p("%s", strict)
	p("\t\tif c.failed() {\n\t\t\treturn collected[R](&c)\n\t\t}\n")
	p("\t\tv, err := fn(%s)\n\t\treturn fromRelativeError(v, err, at)\n\t}}\n}\n", vals)

	ptypes := types
	if n > 0 {
		ptypes += ", "
	}
	p("\n// AndThenWithPath is AndThen for a function that is given the path of the\n// object, so it can report an issue at that path or beside it. Unlike\n// AndThen, it does not move the issues fn returns: their paths are kept as fn\n// gives them, so build them from the path it was given, as at.Key(\"end\").\n")
	p("func (o %s%s) AndThenWithPath[R any](fn func(%sPath) (R, error)) Decoder[any, R] {\n", object, use, ptypes)
	p("\trequireArgument(fn != nil, \"%s.AndThenWithPath\", \"fn\")\n", "Object")
	p("\treturn Decoder[any, R]{func(in any, at Path) outcome[R] {\n")
	p("\t\tm, issue := openObject(in, at)\n\t\tif issue != nil {\n\t\t\treturn invalid[R](*issue)\n\t\t}\n")
	p("\t\tvar c collector\n")
	for i := range n {
		p("\t\tv%d := read(&c, o.f.p%d, in, m, at)\n", i, i)
	}
	p("%s", strict)
	p("\t\tif c.failed() {\n\t\t\treturn collected[R](&c)\n\t\t}\n")
	valsAt := vals
	if n > 0 {
		valsAt += ", "
	}
	p("\t\tv, err := fn(%sat)\n\t\treturn fromAbsoluteError(v, err)\n\t}}\n}\n", valsAt)
}
