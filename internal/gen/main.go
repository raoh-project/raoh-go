// Command gen writes fields_gen.go: the field sets and object builders for
// 0 to raoh.MaxFields fields.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

const max = 16

var letters = strings.Split("ABCDEFGHIJKLMNOP", "")

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen. DO NOT EDIT.\n\npackage raoh\n\nimport \"slices\"\n")
	for n := 0; n <= max; n++ {
		writeArity(&b, n)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("%v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile("fields_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// params returns "[A, B any]" and "[A, B]" for n type parameters, or "" for 0.
func params(n int) (decl, use string) {
	if n == 0 {
		return "", ""
	}
	ls := strings.Join(letters[:n], ", ")
	return "[" + ls + " any]", "[" + ls + "]"
}

func join(n int, f func(i int) string) string {
	s := make([]string, n)
	for i := range n {
		s[i] = f(i)
	}
	return strings.Join(s, ", ")
}

func writeArity(b *bytes.Buffer, n int) {
	decl, use := params(n)
	fields := fmt.Sprintf("fields%d", n)
	object := fmt.Sprintf("object%d", n)
	p := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }

	p("\n// %s is a set of %d fields.\ntype %s%s struct {\n\tnames []string\n", fields, n, fields, decl)
	for i := range n {
		p("\tp%d part[%s]\n", i, letters[i])
	}
	p("}\n")

	if n < max {
		next := letters[n]
		nextUse := "[" + strings.Join(letters[:n+1], ", ") + "]"
		p("\n// Field returns the set with one more field, name, read with src.\n")
		p("func (f %s%s) Field[%s any](name string, src FieldSource[%s]) fields%d%s {\n", fields, use, next, next, n+1, nextUse)
		p("\treturn fields%d%s{append(slices.Clip(f.names), name)", n+1, nextUse)
		for i := range n {
			p(", f.p%d", i)
		}
		p(", toPart(name, src)}\n}\n")
	}

	p("\nfunc (f %s%s) object() %s%s { return %s%s{f: f} }\n", fields, use, object, use, object, use)

	p("\n// %s builds the decoder of an object of %d fields.\ntype %s%s struct {\n\tf      %s%s\n\tstrict bool\n}\n", object, n, object, decl, fields, use)

	p("\n// Strict reports unknown_field for each member the fields do not name.\n")
	p("func (o %s%s) Strict() %s%s {\n\to.strict = true\n\treturn o\n}\n", object, use, object, use)

	args := join(n, func(i int) string { return fmt.Sprintf("v%d %s", i, letters[i]) })
	vals := join(n, func(i int) string { return fmt.Sprintf("v%d", i) })
	types := join(n, func(i int) string { return letters[i] })

	p("\n// Map returns the decoder that builds the value with fn once every field\n// has decoded.\n")
	p("func (o %s%s) Map[R any](fn func(%s) R) Decoder[any, R] {\n", object, use, types)
	p("\treturn o.AndThen(func(%s) (R, error) { return fn(%s), nil })\n}\n", args, vals)

	p("\n// AndThen returns the decoder that builds the value with fn once every\n// field has decoded. Issues fn returns (see Invalid) are reported at the\n// object; any other error stops the decode.\n")
	p("func (o %s%s) AndThen[R any](fn func(%s) (R, error)) Decoder[any, R] {\n", object, use, types)
	p("\treturn Decoder[any, R]{func(in any, at Path) outcome[R] {\n")
	p("\t\tm, issue := openObject(in, at)\n\t\tif issue != nil {\n\t\t\treturn invalid[R](*issue)\n\t\t}\n")
	if n > 0 {
		p("\t\tvar c collector\n")
		for i := range n {
			p("\t\tv%d := read(&c, o.f.p%d, m, at)\n", i, i)
		}
	} else {
		p("\t\tvar c collector\n")
	}
	p("\t\tif o.strict {\n\t\t\tc.unknown(m, at, o.f.names)\n\t\t}\n")
	p("\t\tif c.failed() {\n\t\t\treturn collected[R](&c)\n\t\t}\n")
	p("\t\tv, err := fn(%s)\n\t\treturn fromRelativeError(v, err, at)\n\t}}\n}\n", vals)

	ptypes := types
	if n > 0 {
		ptypes += ", "
	}
	p("\n// AndThenWithPath is AndThen for a function that is given the path of the\n// object, so it can report an issue at that path or beside it. Unlike\n// AndThen, it does not move the issues fn returns: their paths are kept as fn\n// gives them, so build them from the path it was given, as at.Key(\"end\").\n")
	p("func (o %s%s) AndThenWithPath[R any](fn func(%sPath) (R, error)) Decoder[any, R] {\n", object, use, ptypes)
	p("\treturn Decoder[any, R]{func(in any, at Path) outcome[R] {\n")
	p("\t\tm, issue := openObject(in, at)\n\t\tif issue != nil {\n\t\t\treturn invalid[R](*issue)\n\t\t}\n")
	p("\t\tvar c collector\n")
	for i := range n {
		p("\t\tv%d := read(&c, o.f.p%d, m, at)\n", i, i)
	}
	p("\t\tif o.strict {\n\t\t\tc.unknown(m, at, o.f.names)\n\t\t}\n")
	p("\t\tif c.failed() {\n\t\t\treturn collected[R](&c)\n\t\t}\n")
	valsAt := vals
	if n > 0 {
		valsAt += ", "
	}
	p("\t\tv, err := fn(%sat)\n\t\treturn fromAbsoluteError(v, err)\n\t}}\n}\n", valsAt)
}
